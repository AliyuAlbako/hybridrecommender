def coverage(top_n=10):
    all_products = Product.objects.count()
    recommended_products = set()

    for uid in Rating.objects.values_list("user_id", flat=True).distinct():
        recs = get_hybrid_recommendations(user_id=uid, top_n=top_n)["internal"]
        recommended_products.update([p.id for p in recs])

    return {"Coverage": len(recommended_products) / all_products if all_products else 0}


def diversity(top_n=10):
    """
    Diversity = 1 - avg Jaccard similarity of recommendation lists.
    """
    users = Rating.objects.values_list("user_id", flat=True).distinct()
    rec_lists = []

    for uid in users:
        recs = get_hybrid_recommendations(user_id=uid, top_n=top_n)["internal"]
        rec_lists.append(set([p.id for p in recs]))

    if len(rec_lists) < 2:
        return {"Diversity": 0}

    sims = []
    for i in range(len(rec_lists)):
        for j in range(i+1, len(rec_lists)):
            inter = len(rec_lists[i].intersection(rec_lists[j]))
            union = len(rec_lists[i].union(rec_lists[j]))
            sims.append(inter / union if union else 0)

    return {"Diversity": 1 - np.mean(sims) if sims else 0}


def novelty(top_n=10):
    """
    Novelty = avg inverse popularity of recommended items.
    """
    interactions = UserInteraction.objects.values("product_id").annotate(count=Count("id"))
    popularity = {i["product_id"]: i["count"] for i in interactions}

    users = Rating.objects.values_list("user_id", flat=True).distinct()
    novelties = []

    for uid in users:
        recs = get_hybrid_recommendations(user_id=uid, top_n=top_n)["internal"]
        for p in recs:
            freq = popularity.get(p.id, 1)
            novelties.append(1 / (1 + np.log(1 + freq)))

    return {"Novelty": np.mean(novelties) if novelties else 0}


def engagement(top_n=10):
    """
    Engagement = % of recommended items that were interacted with.
    """
    users = Rating.objects.values_list("user_id", flat=True).distinct()
    hits, total = 0, 0

    for uid in users:
        recs = get_hybrid_recommendations(user_id=uid, top_n=top_n)["internal"]
        recommended_items = {p.id for p in recs}
        interacted = set(UserInteraction.objects.filter(user_id=uid).values_list("product_id", flat=True))

        hits += len(recommended_items.intersection(interacted))
        total += len(recommended_items)

    return {"Engagement": hits / total if total else 0}


