def evaluate_prediction_accuracy():
    """
    Offline evaluation using ratings:
    Compare actual ratings vs mean baseline predictions.
    Replace baseline with CF/ML predictions if implemented.
    """
    ratings = list(Rating.objects.all().values("user_id", "product_id", "rating"))
    if not ratings:
        return {}

    # For now, baseline predictor = average rating of product
    product_means = {}
    for r in ratings:
        product_means.setdefault(r["product_id"], []).append(r["rating"])
    product_means = {pid: np.mean(vals) for pid, vals in product_means.items()}

    y_true = []
    y_pred = []
    for r in ratings:
        y_true.append(r["rating"])
        y_pred.append(product_means.get(r["product_id"], 3))  # fallback avg = 3

    rmse = sqrt(mean_squared_error(y_true, y_pred))
    mae = mean_absolute_error(y_true, y_pred)

    return {"RMSE": rmse, "MAE": mae}


def precision_recall_at_k(k=5):
    """
    Evaluate precision@k and recall@k using interactions.
    """
    users = Rating.objects.values_list("user_id", flat=True).distinct()
    precisions, recalls = [], []

    for uid in users:
        user_ratings = Rating.objects.filter(user_id=uid)
        relevant_items = {r.product_id for r in user_ratings if r.rating >= 4}

        recs = get_hybrid_recommendations(user_id=uid, top_n=k)["internal"]
        recommended_items = {p.id for p in recs}

        hits = relevant_items.intersection(recommended_items)

        if recommended_items:
            precisions.append(len(hits) / len(recommended_items))
        if relevant_items:
            recalls.append(len(hits) / len(relevant_items))

    precision = np.mean(precisions) if precisions else 0
    recall = np.mean(recalls) if recalls else 0

    return {"Precision@K": precision, "Recall@K": recall}

