import numpy as np
from django.db.models import Avg, Count
from recommender.models import Rating, UserInteraction, Product
from recommender.recommendation.hybrid import get_hybrid_recommendations
from sklearn.metrics import mean_squared_error, mean_absolute_error
from math import sqrt

